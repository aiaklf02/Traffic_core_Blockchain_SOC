// getOrCreateSensor récupère un capteur ou le crée automatiquement s'il n'existe pas
func (c *SensorDataContract) getOrCreateSensor(ctx contractapi.TransactionContextInterface, sensorID string, sensorType SensorType) (*Sensor, error) {
	sensorJSON, err := ctx.GetStub().GetState(sensorID)
	if err != nil {
		return nil, fmt.Errorf("erreur de lecture du ledger: %v", err)
	}

	// Si le capteur existe, le retourner
	if sensorJSON != nil {
		var sensor Sensor
		err = json.Unmarshal(sensorJSON, &sensor)
		if err != nil {
			return nil, fmt.Errorf("erreur de désérialisation: %v", err)
		}
		return &sensor, nil
	}

	// Créer automatiquement le capteur
	sensor := Sensor{
		DocType:         "sensor",
		ID:              sensorID,
		Name:            fmt.Sprintf("Auto-created %s sensor %s", sensorType, sensorID),
		Type:            sensorType,
		Status:          SensorStatusActive,
		Location:        GeoPoint{Latitude: 33.5731, Longitude: -7.5898},
		RoadID:          "ROAD-001",
		Manufacturer:    "AutoGenerated",
		Model:           "SIM-100",
		FirmwareVersion: "1.0.0",
		InstallDate:     time.Now(),
		LastMaintenance: time.Now(),
		LastReading:     time.Now(),
		BatteryLevel:    100.0,
		SignalStrength:  100.0,
		ReadingInterval: 60,
		CreatedAt:       time.Now(),
		CreatedBy:       "SIMULATOR",
		Organization:    "SimulationNetwork",
	}

	newSensorJSON, err := json.Marshal(sensor)
	if err != nil {
		return nil, fmt.Errorf("erreur de sérialisation: %v", err)
	}

	err = ctx.GetStub().PutState(sensorID, newSensorJSON)
	if err != nil {
		return nil, fmt.Errorf("erreur d'écriture du capteur: %v", err)
	}

	return &sensor, nil
}

// RecordReading enregistre une nouvelle lecture de capteur
func (c *SensorDataContract) RecordReading(ctx contractapi.TransactionContextInterface,
	readingID, sensorID string, dataJSON string, quality string) error {

	// Récupérer ou créer le capteur automatiquement
	sensor, err := c.getOrCreateSensor(ctx, sensorID, SensorTypeTraffic)
	if err != nil {
		return err
	}

	// Vérifier que le capteur est actif
	if sensor.Status != SensorStatusActive {
		return fmt.Errorf("le capteur %s n'est pas actif (statut: %s)", sensorID, sensor.Status)
	}

	// Parser les données
	var data map[string]interface{}
	err = json.Unmarshal([]byte(dataJSON), &data)
	if err != nil {
		return fmt.Errorf("erreur de parsing des données: %v", err)
	}

	// Obtenir l'identité du validateur
	validatedBy, err := ctx.GetClientIdentity().GetID()
	if err != nil {
		validatedBy = "SYSTEM"
	}

	reading := SensorReading{
		DocType:     "sensorReading",
		ID:          readingID,
		SensorID:    sensorID,
		Timestamp:   time.Now(),
		Data:        data,
		Quality:     DataQuality(quality),
		RawValue:    dataJSON,
		ProcessedAt: time.Now(),
		ValidatedBy: validatedBy,
	}

	readingJSON, err := json.Marshal(reading)
	if err != nil {
		return fmt.Errorf("erreur de sérialisation: %v", err)
	}

	// Mettre à jour le timestamp de dernière lecture du capteur
	sensor.LastReading = time.Now()
	sensorJSON, err := json.Marshal(sensor)
	if err == nil {
		ctx.GetStub().PutState(sensorID, sensorJSON)
	}

	return ctx.GetStub().PutState(readingID, readingJSON)
}

// RecordTrafficReading enregistre une lecture de capteur de trafic
func (c *SensorDataContract) RecordTrafficReading(ctx contractapi.TransactionContextInterface,
	readingID, sensorID string, vehicleCount int, averageSpeed float64,
	occupancy float64, flow int, laneNumber int) error {

	// Récupérer ou créer le capteur automatiquement
	sensor, err := c.getOrCreateSensor(ctx, sensorID, SensorTypeTraffic)
	if err != nil {
		return err
	}

	trafficData := TrafficSensorData{
		VehicleCount: vehicleCount,
		AverageSpeed: averageSpeed,
		Occupancy:    occupancy,
		Flow:         flow,
		LaneNumber:   laneNumber,
	}

	data := map[string]interface{}{
		"vehicleCount": trafficData.VehicleCount,
		"averageSpeed": trafficData.AverageSpeed,
		"occupancy":    trafficData.Occupancy,
		"flow":         trafficData.Flow,
		"laneNumber":   trafficData.LaneNumber,
	}

	// Déterminer la qualité des données
	quality := DataQualityHigh
	if vehicleCount < 0 || averageSpeed < 0 || occupancy < 0 || occupancy > 100 {
		quality = DataQualityInvalid
	}

	validatedBy, _ := ctx.GetClientIdentity().GetID()

	reading := SensorReading{
		DocType:     "sensorReading",
		ID:          readingID,
		SensorID:    sensorID,
		Timestamp:   time.Now(),
		Data:        data,
		Quality:     quality,
		ProcessedAt: time.Now(),
		ValidatedBy: validatedBy,
	}

	readingJSON, err := json.Marshal(reading)
	if err != nil {
		return fmt.Errorf("erreur de sérialisation: %v", err)
	}

	// Mettre à jour le capteur
	sensor.LastReading = time.Now()
	sensorJSON, _ := json.Marshal(sensor)
	ctx.GetStub().PutState(sensorID, sensorJSON)

	// Émettre un événement si congestion détectée
	if occupancy > 80 {
		eventPayload := fmt.Sprintf(`{"sensorId":"%s","roadId":"%s","occupancy":%.2f,"alert":"HIGH_CONGESTION"}`,
			sensorID, sensor.RoadID, occupancy)
		ctx.GetStub().SetEvent("CongestionAlert", []byte(eventPayload))
	}

	return ctx.GetStub().PutState(readingID, readingJSON)
}

