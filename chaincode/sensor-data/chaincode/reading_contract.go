// GetReadingsBySensor récupère les lectures d'un capteur
func (c *SensorDataContract) GetReadingsBySensor(ctx contractapi.TransactionContextInterface,
	sensorID string) ([]*SensorReading, error) {

	queryString := fmt.Sprintf(`{"selector":{"docType":"sensorReading","sensorId":"%s"}}`, sensorID)

	resultsIterator, err := ctx.GetStub().GetQueryResult(queryString)
	if err != nil {
		return nil, fmt.Errorf("erreur de requête: %v", err)
	}
	defer resultsIterator.Close()

	var readings []*SensorReading
	for resultsIterator.HasNext() {
		queryResult, err := resultsIterator.Next()
		if err != nil {
			return nil, err
		}

		var reading SensorReading
		err = json.Unmarshal(queryResult.Value, &reading)
		if err != nil {
			return nil, err
		}
		readings = append(readings, &reading)
	}

	return readings, nil
}

