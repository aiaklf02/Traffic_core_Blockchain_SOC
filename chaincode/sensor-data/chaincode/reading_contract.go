// BatchRecordReadings enregistre plusieurs lectures en lot
func (c *SensorDataContract) BatchRecordReadings(ctx contractapi.TransactionContextInterface,
	readingsJSON string) error {

	var readings []struct {
		ReadingID string                 `json:"readingId"`
		SensorID  string                 `json:"sensorId"`
		Data      map[string]interface{} `json:"data"`
		Quality   string                 `json:"quality"`
	}

	err := json.Unmarshal([]byte(readingsJSON), &readings)
	if err != nil {
		return fmt.Errorf("erreur de parsing des lectures: %v", err)
	}

	validatedBy, _ := ctx.GetClientIdentity().GetID()

	for _, r := range readings {
		// Vérifier que le capteur existe
		_, err := c.GetSensor(ctx, r.SensorID)
		if err != nil {
			continue // Skip invalid sensors
		}

		reading := SensorReading{
			DocType:     "sensorReading",
			ID:          r.ReadingID,
			SensorID:    r.SensorID,
			Timestamp:   time.Now(),
			Data:        r.Data,
			Quality:     DataQuality(r.Quality),
			ProcessedAt: time.Now(),
			ValidatedBy: validatedBy,
		}

		readingJSON, err := json.Marshal(reading)
		if err != nil {
			continue
		}

		ctx.GetStub().PutState(r.ReadingID, readingJSON)
	}

	// Émettre un événement
	eventPayload := fmt.Sprintf(`{"batchSize":%d,"processed":true}`, len(readings))
	ctx.GetStub().SetEvent("BatchReadingsRecorded", []byte(eventPayload))

	return nil
}

// DeleteOldReadings supprime les anciennes lectures (nettoyage)
func (c *SensorDataContract) DeleteOldReadings(ctx contractapi.TransactionContextInterface,
	sensorID string, beforeTimestamp string) error {

	queryString := fmt.Sprintf(`{"selector":{"docType":"sensorReading","sensorId":"%s"}}`, sensorID)

	resultsIterator, err := ctx.GetStub().GetQueryResult(queryString)
	if err != nil {
		return fmt.Errorf("erreur de requête: %v", err)
	}
	defer resultsIterator.Close()

	cutoffTime, err := time.Parse(time.RFC3339, beforeTimestamp)
	if err != nil {
		return fmt.Errorf("format de timestamp invalide: %v", err)
	}

	deletedCount := 0
	for resultsIterator.HasNext() {
		queryResult, err := resultsIterator.Next()
		if err != nil {
			return err
		}

		var reading SensorReading
		err = json.Unmarshal(queryResult.Value, &reading)
		if err != nil {
			continue
		}

		if reading.Timestamp.Before(cutoffTime) {
			ctx.GetStub().DelState(reading.ID)
			deletedCount++
		}
	}

	// Émettre un événement
	eventPayload := fmt.Sprintf(`{"sensorId":"%s","deletedCount":%d}`, sensorID, deletedCount)
	ctx.GetStub().SetEvent("OldReadingsDeleted", []byte(eventPayload))

	return nil
}
